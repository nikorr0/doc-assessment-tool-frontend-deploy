function HelpInteractiveReportBlock() {
  const [reportExpanded, setReportExpanded] = useState(false);

  return (
    <>
      <p>
        <TaskReportToggleButton
          reportText={HELP_DEMO_REPORT_TEXT}
          annotationText={HELP_DEMO_ANNOTATION_TEXT}
          expanded={reportExpanded}
          onToggle={() => setReportExpanded(value => !value)}
        />{" "}
        <UiElementChip label="Показать отчёт" /> появляется, если по задаче есть текст отчёта
        и/или пояснение из загруженного акта. Эти сведения берутся из столбцов акта «Отчет о
        фактическом выполнении поручений» и «Пояснения**». При нажатии на значок под строкой задачи
        раскрывается дополнительная строка, где можно прочитать, что именно было указано в отчётном
        документе.
      </p>
      {reportExpanded ? (
        <div className="help-report-panel-demo" aria-label="Пример раскрытого отчёта по задаче">
          <table className="help-report-panel-demo__table">
            <tbody>
              <TaskReportPanelRow
                reportText={HELP_DEMO_REPORT_TEXT}
                annotationText={HELP_DEMO_ANNOTATION_TEXT}
                colSpan={1}
              />
            </tbody>
          </table>
        </div>
      ) : null}
    </>
  );
}

