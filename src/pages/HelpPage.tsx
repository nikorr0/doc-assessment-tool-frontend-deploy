function StatusTransitionChip({ from, to }: { from: string; to: string }) {
  return (
    <span className="help-status-transition-chip">
      <StatusChip label={from} tone={from === "Выполнено" ? "done" : from === "В работе" ? "progress" : "not-done"} />
      <span className="help-status-transition-arrow" aria-hidden>
        →
      </span>
      <StatusChip label={to} tone={to === "Выполнено" ? "done" : to === "В работе" ? "progress" : "not-done"} />
    </span>
  );
}

